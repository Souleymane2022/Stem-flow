const DICTIONARIES: Record<Locale, Dictionary> = { fr, en, ar };

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

type I18nContextValue = {
  locale: Locale;
  dir: Direction;
  setLocale: (next: Locale) => void;
  t: Translate;
};

const I18nContext = createContext<I18nContextValue | null>(null);

/**
 * Langue préférée du visiteur, lue au montage seulement.
 *
 * Elle ne peut pas servir d'état initial : le rendu serveur ne connaît ni le
 * stockage local ni la langue du navigateur, il produit donc toujours du
 * français. Un client anglophone qui démarrait directement en anglais rendait
 * un arbre différent de celui reçu, et React jetait tout le rendu serveur pour
 * le refaire — un écran blanc de plus au chargement. On part donc du français,
 * comme le serveur, puis on bascule juste après l'hydratation.
 */
function detectPreferredLocale(): Locale {
  if (typeof window === "undefined") return "fr";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (isLocale(stored)) return stored;
  const navigatorLocale = window.navigator.language.slice(0, 2);
  return isLocale(navigatorLocale) ? navigatorLocale : "fr";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const { session, profile } = useAuth();
  const [locale, setLocaleState] = useState<Locale>("fr");

  useEffect(() => {
    const preferred = detectPreferredLocale();
    if (preferred !== "fr") setLocaleState(preferred);
  }, []);

  // Le profil fait autorité au premier chargement d'une session : la préférence
  // enregistrée pendant l'onboarding suit l'utilisateur d'un appareil à l'autre.
  useEffect(() => {
    const stored = typeof window === "undefined" ? null : window.localStorage.getItem(STORAGE_KEY);
    if (stored) return;
    if (isLocale(profile?.preferred_language)) setLocaleState(profile.preferred_language);
  }, [profile?.preferred_language]);

  // `dir` et `lang` sont posés côté client : le shell SSR ne connaît pas encore
  // la langue choisie.
  useEffect(() => {
    const root = document.documentElement;
    root.lang = locale;
    root.dir = directionOf(locale);
  }, [locale]);

  const setLocale = useCallback(
    (next: Locale) => {
      setLocaleState(next);
      if (typeof window !== "undefined") window.localStorage.setItem(STORAGE_KEY, next);
      if (session) {
        void supabase
          .from("profiles")
          .update({ preferred_language: next })
          .eq("id", session.user.id)
          .then(({ error }) => {
            if (error) console.error("[i18n] langue non enregistrée", error);
          });
      }
    },
    [session],
  );

  const t = useCallback<Translate>(
    (key, vars) => {
      // Repli sur le français : une clé absente d'une traduction reste lisible
      // plutôt que d'afficher son identifiant brut.
      const template = DICTIONARIES[locale][key] ?? fr[key] ?? key;
      if (!vars) return template;
      return Object.entries(vars).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
        template,
      );
    },
    [locale],
  );

  const value = useMemo(
    () => ({ locale, dir: directionOf(locale), setLocale, t }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n doit être utilisé dans I18nProvider");
  return ctx;
}

/**
 * Libellés des matières et des niveaux.
 *
 * La valeur stockée en base est française — c'est elle qui sert de clé, dans
 * `contents.category` comme dans les filtres — mais elle n'a pas à s'afficher
 * telle quelle : un écran en anglais montrait « Ingénierie » au milieu de sa
 * propre langue. La correspondance passe par le jeton de la matière, stable
 * quelle que soit la langue d'affichage.
 */
export function useLabels() {
  const { t } = useI18n();
  return useMemo(
    () => ({
      categoryLabel: (category?: string | null) => {
        const token = categoryMeta(category).token;
        return t(`category.${token}` as Key);
      },
      difficultyLabel: (value?: string | null) => {
        const known = DIFFICULTIES.some((d) => d.value === value);
        return t(`difficulty.${known ? value : "debutant"}` as Key);
      },
    }),
    [t],
  );
}
